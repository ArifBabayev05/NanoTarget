// Firebase Hosting + Cloud Functions (2nd gen) target. One HTTPS function serves every route
// (hosting rewrites "**" to it); the static roots the app reads at runtime (web/, sdk/, docs/,
// server/kinematics-model.json) are copied next to the bundle and NT_ROOT points at them.
// Secrets come from .env.local (never committed) and land in functions/.env, which is ignored too.
import { build } from 'esbuild';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';

const FN = 'firebase/functions';
mkdirSync(FN, { recursive: true }); mkdirSync('firebase/public', { recursive: true });
writeFileSync('scripts/ws-stub.js', 'export default class WebSocketUnavailable { constructor() { throw new Error("WebSocket transport disabled; use https:// libsql URLs"); } }\nexport const WebSocket = WebSocketUnavailable;\n');
await build({
  entryPoints: ['server/vercel-entry.ts'], outfile: `${FN}/app.js`, bundle: true, platform: 'node', format: 'esm', target: 'node22',
  sourcemap: false, legalComments: 'none', external: ['node:*'],
  alias: { ws: './scripts/ws-stub.js', '@libsql/isomorphic-ws': './scripts/ws-stub.js' },
  banner: { js: '// generated by scripts/build-firebase.mjs — do not edit' },
});
for (const d of ['web', 'sdk', 'docs']) { rmSync(`${FN}/${d}`, { recursive: true, force: true }); cpSync(d, `${FN}/${d}`, { recursive: true }); }
mkdirSync(`${FN}/server`, { recursive: true }); cpSync('server/kinematics-model.json', `${FN}/server/kinematics-model.json`);
writeFileSync(`${FN}/index.js`, `import { onRequest } from 'firebase-functions/v2/https';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
process.env.NT_ROOT = dirname(fileURLToPath(import.meta.url));
const { handler } = await import('./app.js');
export const app = onRequest({ region: 'us-central1', memory: '512MiB', timeoutSeconds: 30, concurrency: 80, minInstances: 0 }, (req, res) => handler(req, res));
`);
writeFileSync(`${FN}/package.json`, JSON.stringify({ name: 'nanotarget-firebase', private: true, type: 'module', main: 'index.js', engines: { node: '22' }, dependencies: { 'firebase-functions': '^6.4.0', 'firebase-admin': '^13.4.0' } }, null, 2) + '\n');
// environment: what Vercel has, plus the lab key
const env = {};
if (existsSync('.env.local')) for (const line of readFileSync('.env.local', 'utf8').split('\n')) { const m = /^([A-Z_]+)="?([^"]*)"?$/.exec(line.trim()); if (m && !m[1].startsWith('VERCEL')) env[m[1]] = m[2]; }
if (process.env.NT_LAB_KEY) env.NT_LAB_KEY = process.env.NT_LAB_KEY;
writeFileSync(`${FN}/.env`, Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n');
writeFileSync('firebase/public/robots.txt', 'User-agent: *\nAllow: /\n');
console.log(`built ${FN}/app.js + static roots; env keys: ${Object.keys(env).join(', ')}`);
